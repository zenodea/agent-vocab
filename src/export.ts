/**
 * GLOSSARY.md: the session's glossary as plain markdown, for the repo. Other
 * agents and teammates then share the same names. The file carries a marker
 * so a later export knows it is safe to overwrite.
 */

import { type Entry, type Kind, KINDS } from "./glossary.ts";

export const EXPORT_MARKER = "<!-- generated by pi-vocab; edits will be overwritten by /vocab export -->";

const HEADINGS: Record<Kind, string> = {
	term: "Terms",
	concept: "Concepts",
	why: "Why things are the way they are",
	where: "Where things live",
	how: "How to do things",
	gotcha: "Gotchas",
};

/** Render entries grouped by kind, alphabetical within each group. */
export function renderGlossary(entries: Entry[], now = new Date()): string {
	const lines: string[] = [EXPORT_MARKER, "", "# Glossary", "", `Exported ${now.toISOString().slice(0, 10)}. ${entries.length} entries.`, ""];
	for (const kind of KINDS) {
		const group = entries.filter((e) => e.kind === kind && e.definition).sort((a, b) => a.term.localeCompare(b.term));
		if (group.length === 0) continue;
		lines.push(`## ${HEADINGS[kind]}`, "");
		for (const e of group) {
			const see = e.related.length ? ` (see: ${e.related.join(", ")})` : "";
			lines.push(`- **${e.term}**: ${e.definition}${see}`);
		}
		lines.push("");
	}
	if (lines[lines.length - 1] !== "") lines.push("");
	return lines.join("\n");
}

/** True when an existing file was written by us, so overwriting loses nothing. */
export const isOurs = (content: string): boolean => content.startsWith(EXPORT_MARKER);
